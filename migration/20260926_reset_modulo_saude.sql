-- Perfis de saude (master: peso, IMC, agua, dietas)
create table public.tb_saude_perfis (
  id bigint generated by default as identity primary key,
  created_by uuid not null references auth.users(id) on delete cascade,
  nome text not null,
  sexo text not null,
  data_nascimento date not null,
  peso_kg numeric(6,2) not null,
  altura_cm numeric(6,2) not null,
  data_medicao date not null default current_date,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint tb_saude_perfis_id_usuario_key unique (id, created_by),
  constraint tb_saude_perfis_nome_check check (char_length(trim(nome)) between 1 and 120),
  constraint tb_saude_perfis_sexo_check check (sexo in ('feminino', 'masculino', 'outro', 'nao_informado')),
  constraint tb_saude_perfis_data_nascimento_check check (data_nascimento >= date '1900-01-01' and data_nascimento <= current_date),
  constraint tb_saude_perfis_peso_check check (peso_kg between 1 and 500),
  constraint tb_saude_perfis_altura_check check (altura_cm between 30 and 260)
);

comment on table public.tb_saude_perfis is
  'Perfis familiares do modulo Saude; agua e dietas referenciam este id';

create table public.tb_saude_perfil_medidas (
  id bigint generated by default as identity primary key,
  perfil_id bigint not null references public.tb_saude_perfis(id) on delete cascade,
  created_by uuid not null references auth.users(id) on delete cascade,
  peso_kg numeric(6,2) not null,
  altura_cm numeric(6,2) not null,
  imc numeric(5,2) generated always as (round(peso_kg / power(altura_cm / 100, 2), 2)) stored,
  registrado_em timestamptz not null default now()
);

create index tb_saude_perfil_medidas_perfil_tempo_idx
  on public.tb_saude_perfil_medidas (perfil_id, registrado_em desc);

create or replace function public.registrar_saude_perfil_medidas()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  if tg_op = 'INSERT' then
    insert into public.tb_saude_perfil_medidas (
      perfil_id, created_by, peso_kg, altura_cm, registrado_em
    ) values (
      new.id, new.created_by, new.peso_kg, new.altura_cm, now()
    );
  elsif (new.peso_kg, new.altura_cm) is distinct from (old.peso_kg, old.altura_cm) then
    insert into public.tb_saude_perfil_medidas (
      perfil_id, created_by, peso_kg, altura_cm, registrado_em
    ) values (
      new.id, new.created_by, new.peso_kg, new.altura_cm, now()
    );
  elsif new.data_medicao is distinct from old.data_medicao then
    update public.tb_saude_perfil_medidas
    set registrado_em = (new.data_medicao + time '12:00') at time zone 'America/Sao_Paulo'
    where id = (
      select id
      from public.tb_saude_perfil_medidas
      where perfil_id = new.id and created_by = new.created_by
      order by id desc
      limit 1
    );
  end if;
  return new;
end;
$$;

create trigger tb_saude_perfis_registrar_medidas
  after insert or update on public.tb_saude_perfis
  for each row execute function public.registrar_saude_perfil_medidas();

