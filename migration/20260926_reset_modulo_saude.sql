  refeicoes jsonb not null default '[]'::jsonb,
  observacoes text not null default '',
  perfil_id bigint references public.tb_saude_perfis(id) on delete cascade,
  source_file text not null default 'Cadastro manual',
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint tb_saude_dietas_slug_key unique (slug),
  constraint tb_saude_dietas_slug_check check (slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$'),
  constraint tb_saude_dietas_titulo_check check (char_length(trim(titulo)) between 1 and 160),
  constraint tb_saude_dietas_objetivo_check check (char_length(trim(objetivo)) between 1 and 120),
  constraint tb_saude_dietas_duracao_check check (duracao_dias between 1 and 31),
