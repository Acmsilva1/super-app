    from public.tb_saude_dietas d join seed_cardapio_20261011_targets t on t.perfil_id=d.perfil_id
    where d.source_file=v_source and d.slug='seed-cardapio-1600-20261011-perfil-' || t.perfil_id::text;
  insert into public.tb_saude_dietas_seed_backup(run_id,dieta_id,perfil_id,created_by,dieta,agendas)
    select v_run,dieta_id,perfil_id,v_owner,dieta,agendas from seed_cardapio_20261011_previous;
  delete from public.tb_saude_dietas d using seed_cardapio_20261011_previous p where d.id=p.dieta_id;
  select jsonb_agg(jsonb_build_object('numero',ordinality,'titulo',value->>'titulo',
    'jejum_horas',0,'quantidade_refeicoes',5,'carboidrato','','conteudo','') order by ordinality)
