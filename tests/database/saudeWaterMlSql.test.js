  expect((await record('request-a')).rows[0].result).toMatchObject({realizado_ml:400,duplicate:true});
  await record('request-c',500);
  expect((await db.query('select realizado_ml,realizado_doses from tb_saude_agua_logs')).rows[0]).toEqual({realizado_ml:900,realizado_doses:3});
  await record('request-litre',1000);await record('request-two-litres',2000);
